import '../models/role.dart';

/// Подробная памятка по роли: что делать ночью, что днём, за что бороться
/// и на чём обычно горят новички.
///
/// Показывается игроку при получении роли и доступна в любой момент
/// по кнопке «Моя роль».
class RoleGuide {
  final String goal;
  final String atNight;
  final String atDay;
  final String winCondition;
  final List<String> tips;

  const RoleGuide({
    required this.goal,
    required this.atNight,
    required this.atDay,
    required this.winCondition,
    this.tips = const [],
  });

  static RoleGuide of(RoleType type) {
    switch (type) {
      case RoleType.mafia:
        return const RoleGuide(
          goal: 'Вы в команде мафии. Ваша задача — по ночам устранять '
              'горожан, а днём не выдать себя.',
          atNight: 'Просыпаетесь вместе с командой и выбираете жертву. '
              'Вы видите своих союзников — их имена показаны на карточке. '
              'Если мнения разошлись, решает голос дона.',
          atDay: 'Обсуждаете наравне со всеми и голосуете. Ваша цель — '
              'отвести подозрения от своих и подставить мирных.',
          winCondition: 'Мафии должно стать не меньше, чем всех остальных '
              'игроков вместе взятых.',
          tips: [
            'Не защищайте союзника слишком рьяно — это заметно.',
            'Иногда полезно проголосовать против своего, чтобы снять '
                'с себя подозрения.',
            'Помните, кого «убила» команда: случайная оговорка выдаёт.',
          ],
        );

      case RoleType.don:
        return const RoleGuide(
          goal: 'Вы глава мафии. Ведёте команду и принимаете решение, '
              'кого устранить.',
          atNight: 'Просыпаетесь с мафией. Ваш голос решающий: если команда '
              'не сошлась во мнении, жертвой станет тот, кого выбрали вы.',
          atDay: 'Играете как обычный горожанин. Ваше преимущество: '
              'при проверке комиссар видит вас как мирного жителя.',
          winCondition: 'Мафии должно стать не меньше, чем всех остальных '
              'игроков вместе взятых.',
          tips: [
            'Проверка комиссара покажет вас мирным — этим можно смело '
                'давить в споре.',
            'Берегите себя: без дона команда теряет решающий голос.',
            'Не спешите брать инициативу в первый же день.',
          ],
        );

      case RoleType.doctor:
        return const RoleGuide(
          goal: 'Вы на стороне города. Спасаете тех, на кого этой ночью '
              'нацелилась мафия или маньяк.',
          atNight: 'Выбираете одного игрока — он переживёт эту ночь. '
              'Защита действует и от мафии, и от маньяка. '
              'Нельзя лечить одного и того же две ночи подряд.',
          atDay: 'Обсуждаете и голосуете как обычный житель.',
          winCondition: 'Город побеждает, когда не осталось ни мафии, '
              'ни маньяка.',
          tips: [
            'Себя лечить можно, но не увлекайтесь: город ждёт спасений.',
            'Удачное спасение — сильная улика: значит, мафия целилась '
                'именно в этого игрока.',
            'Не раскрывайтесь рано — вас устранят первым.',
          ],
        );

      case RoleType.commissioner:
        return const RoleGuide(
          goal: 'Вы на стороне города. По ночам вычисляете мафию.',
          atNight: 'Выбираете игрока для проверки. Ведущий узнает, '
              'состоит ли он в мафии. Важно: дон при проверке выглядит '
              'как мирный житель.',
          atDay: 'Ваша задача — донести информацию до города, не выдав '
              'себя слишком рано.',
          winCondition: 'Город побеждает, когда не осталось ни мафии, '
              'ни маньяка.',
          tips: [
            'Раскрывшись, вы почти наверняка погибнете следующей ночью — '
                'выбирайте момент.',
            'Чистая проверка тоже ценна: она сужает круг подозреваемых.',
            'Проверенный «мирный» может оказаться доном.',
          ],
        );

      case RoleType.prostitute:
        return const RoleGuide(
          goal: 'Вы на стороне города. Мешаете другим совершать ночные ходы.',
          atNight: 'Выбираете игрока — он пропускает свой ночной ход. '
              'Заблокируете мафию — убийства не будет. Но заблокируете '
              'доктора — он никого не спасёт.',
          atDay: 'Обсуждаете и голосуете как обычный житель.',
          winCondition: 'Город побеждает, когда не осталось ни мафии, '
              'ни маньяка.',
          tips: [
            'Блокировка применяется раньше всех остальных действий.',
            'Осторожно: заблокировав комиссара или доктора, вы играете '
                'на руку мафии.',
            'Ночь без жертв — возможно, ваша заслуга.',
          ],
        );

      case RoleType.maniac:
        return const RoleGuide(
          goal: 'Вы мирный житель с тёмной тайной: по ночам вы убиваете. '
              'Но победить вы можете только вместе с городом — когда '
              'мафии не останется.',
          atNight: 'Выбираете жертву и убиваете её независимо от мафии. '
              'За ночь может погибнуть двое: ваша цель и цель мафии.',
          atDay: 'Обсуждаете и голосуете как обычный житель. Вам тоже '
              'выгодно вычислить мафию.',
          winCondition: 'Город побеждает, когда не осталось ни одного '
              'мафиози. Вы побеждаете вместе с городом.',
          tips: [
            'Убивая горожан, вы ослабляете свою же сторону — бейте с умом.',
            'Идеальная цель — тот, кого вы подозреваете в мафии.',
            'Доктор может спасти вашу жертву — учитывайте это.',
          ],
        );

      case RoleType.civilian:
        return const RoleGuide(
          goal: 'Вы мирный житель. У вас нет ночных способностей — '
              'только голос и здравый смысл.',
          atNight: 'Спите. Ваш экран останется пустым до рассвета — '
              'это нормально.',
          atDay: 'Ваше главное оружие. Слушайте, спорьте, ищите '
              'противоречия и голосуйте.',
          winCondition: 'Город побеждает, когда не осталось ни мафии, '
              'ни маньяка.',
          tips: [
            'Следите, кто кого защищает — мафия часто прикрывает своих.',
            'Не молчите: пассивных игроков выводят из игры первыми.',
            'Запоминайте, кто как голосовал в прошлых раундах.',
          ],
        );
    }
  }
}
